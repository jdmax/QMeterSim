"""Proton NMR absorption lineshape, measured and polarization dependent, with its exact Kramers-Kronig dispersion.

Generated by web/tools/make_proton_data.py; edit that script, not this file.

The shape comes from proton event logs of a 5 T polarized target (212.9 MHz, October 2022): 12 fit-subtracted
lines spanning P = 0.24 to 0.79, 8 single sweeps from the spin-up and 4 averages of the sweeps
as the polarization decayed. As P grows the line shifts up in frequency and sharpens on its high-frequency side,
the polarization-dependent local field of the polarized sample. The model is

    g(x; P) = A0(x - s P) + P A1(x - s P),     s = 24.81 kHz per unit polarization,

with x the offset from the Larmor frequency f0 in kHz. The whole line shifts by s P (its centroid follows this
to 0.5 kHz in the data), and its shape about that point changes linearly with P. A0 and A1 come from a
least squares fit to the 12 lines, which reproduces each within 5% of its peak. Extrapolated to
P = 0, A0 is nearly symmetric, and for negative P the shift and the sharp edge reverse, as spin-temperature
theory expects. Neither was imposed. The integral of A1 is zero, so the area does not depend on P. Faint tails
are smoothed and both ends tapered to zero; samples every 1.5747 kHz.

Between samples the shape is a straight line, a sum of triangular "hat" functions. The Hilbert transform of a
hat of half-width h centered at 0 is
    H[hat](x) = [F(x+h) - 2 F(x) + F(x-h)] / (pi h),   F(x) = x ln|x|,
so the dispersion chi' = -H[chi''] is exact, with the correct 1/x tails far from the line.
"""

