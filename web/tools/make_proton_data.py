"""Build the proton lineshape model and the proton page's data from NMR event logs.

    python web/tools/make_proton_data.py [log directory, default temp/]

The logs (one JSON event per line, as written by the JLab NMR DAQ) are not in the repository; temp/ is
git-ignored. From them this script

  1. picks the example lines: every single sweep of the spin-up (P > 0.05 before the polarization plateau)
     and averages of the plateau and decay sweeps in four polarization bins,
  2. fits the polarization-dependent lineshape g(x; P) = A0(x - sP) + P A1(x - sP), and
  3. writes web/proton_lineshape.py (the simulator's model) and web/proton_data.json (the proton page's data).
"""

import glob
import json
import os
import sys
import textwrap
from datetime import datetime, timezone

import numpy as np

WEB = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = os.path.dirname(WEB)

N_SPINUP = 8                                   # single sweeps taken during the spin-up
DECAY_BINS = ((0.785, 0.80), (0.77, 0.785), (0.755, 0.77), (0.74, 0.755))
LINE_REGION_MHZ = (212.62, 213.06)             # the line; outside it the fit-subtracted sweep is noise
CENTROID_REGION_MHZ = (212.6, 213.1)
GRID_HALF = 190                                # model grid: +-190 samples about the P = 0 center
PAGE_REGION_KHZ = (-300, 220)                  # range of the example lines written for the page


def load_events(directory):
    t, pol, y = [], [], []
    f = None
    for fn in sorted(glob.glob(os.path.join(directory, '*.txt'))):
        with open(fn, encoding='utf-8') as fh:
            for line in fh:
                line = line.strip()
                if not line:
                    continue
                try:
                    e = json.loads(line)
                except json.JSONDecodeError:
                    continue
                fs = e.get('fitsub')
                if not fs or e.get('pol') is None:
                    continue
                if f is None:
                    f = np.asarray(e['freq_list'], float)
                if len(fs) != len(f):
                    continue
                t.append(e.get('stop_stamp', 0.0))
                pol.append(e['pol'])
                y.append(fs)
    if f is None:
        sys.exit(f"no events found in {directory}")
    o = np.argsort(t)
    return np.asarray(t)[o], np.asarray(pol)[o], -np.asarray(y)[o], f   # sign flipped: absorption > 0


def example_lines(t, pol, y):
    sel = np.nonzero(pol > 0.05)[0]
    lines = [dict(t=t[i], pol=pol[i], n=1, kind='spin-up', y=y[i]) for i in sel[:N_SPINUP]]
    rest = sel[N_SPINUP:]
    for a, b in DECAY_BINS:
        m = rest[(pol[rest] >= a) & (pol[rest] < b)]
        if len(m):
            lines.append(dict(t=t[m].mean(), pol=pol[m].mean(), n=len(m), kind='plateau and decay',
                              y=y[m].mean(0)))
    return lines


def fit_model(lines, f):
    h = 1e3 * (f[1] - f[0])
    Ps = np.array([ln['pol'] for ln in lines])
    w = (f > CENTROID_REGION_MHZ[0]) & (f < CENTROID_REGION_MHZ[1])
    cents = np.array([np.sum((ln['y'] * f)[w]) / np.sum(ln['y'][w]) for ln in lines])
    slope, c0 = np.polyfit(Ps, cents, 1)
    slope_khz = 1e3 * slope
    xg = h * np.arange(-GRID_HALF, GRID_HALF + 1)
    G = []
    for ln in lines:
        s = ln['y'].copy()
        s[(f < LINE_REGION_MHZ[0]) | (f > LINE_REGION_MHZ[1])] = 0
        gi = np.interp(xg, 1e3 * (f - c0), s, left=0, right=0)
        G.append(gi / (np.sum(gi) * h))
    G = np.array(G)

    def shift(g, d):
        return np.interp(xg + d, xg, g, left=0, right=0)

    aligned = np.array([shift(g, slope_khz * p) for g, p in zip(G, Ps)])
    X = np.stack([np.ones_like(Ps), Ps], 1)
    (A0, A1), *_ = np.linalg.lstsq(X, aligned, rcond=None)
    pk = A0.max()
    sm = lambda v: np.convolve(np.pad(v, 2, mode='edge'), np.ones(5) / 5, mode='valid')
    tail = A0 < 0.02 * pk                      # faint tails: smooth both parts
    A0[tail] = sm(A0)[tail]
    A1[tail] = sm(A1)[tail]
    n_t = 12                                   # taper the ends to zero
    tp = np.ones_like(xg)
    tp[:n_t] = np.linspace(0, 1, n_t)
    tp[-n_t:] = np.linspace(1, 0, n_t)
    A0 *= tp
    A1 *= tp
    A1 -= A0 * (A1.sum() / A0.sum())           # area independent of P
    A0, A1 = A0 / pk, A1 / pk
    errs = [float(np.max(abs(shift(A0 + p * A1, -slope_khz * p) * pk - g)) / g.max()) for g, p in zip(G, Ps)]
    return dict(c0=float(c0), slope_khz=float(slope_khz), step=float(h), A0=A0, A1=A1,
                centroids=cents, max_err=max(errs))


MODULE = '''"""Proton NMR absorption lineshape, measured and polarization dependent, with its exact Kramers-Kronig dispersion.

Generated by web/tools/make_proton_data.py; edit that script, not this file.

The shape comes from proton event logs of a 5 T polarized target (212.9 MHz, October 2022): {n_lines} fit-subtracted
lines spanning P = {pmin:.2f} to {pmax:.2f}, {n_spin} single sweeps from the spin-up and {n_avg} averages of the sweeps
as the polarization decayed. As P grows the line shifts up in frequency and sharpens on its high-frequency side,
the polarization-dependent local field of the polarized sample. The model is

    g(x; P) = A0(x - s P) + P A1(x - s P),     s = {slope:.2f} kHz per unit polarization,

with x the offset from the Larmor frequency f0 in kHz. The whole line shifts by s P (its centroid follows this
to {cent_rms:.1f} kHz in the data), and its shape about that point changes linearly with P. A0 and A1 come from a
least squares fit to the {n_lines} lines, which reproduces each within {max_err:.0f}% of its peak. Extrapolated to
P = 0, A0 is nearly symmetric, and for negative P the shift and the sharp edge reverse, as spin-temperature
theory expects. Neither was imposed. The integral of A1 is zero, so the area does not depend on P. Faint tails
are smoothed and both ends tapered to zero; samples every {step:.4f} kHz.

Between samples the shape is a straight line, a sum of triangular "hat" functions. The Hilbert transform of a
hat of half-width h centered at 0 is
    H[hat](x) = [F(x+h) - 2 F(x) + F(x-h)] / (pi h),   F(x) = x ln|x|,
so the dispersion chi' = -H[chi''] is exact, with the correct 1/x tails far from the line.
"""

import numpy as np

STEP_KHZ = {step:.6f}            # sample spacing
SHIFT_KHZ_PER_POL = {slope:.4f}   # shift of the line per unit polarization
KNOTS_KHZ = STEP_KHZ * np.arange(-{half}, {half_p1})   # offsets from the P = 0 line center
A0 = np.array([
{A0}
])
A1 = np.array([
{A1}
])
AREA_KHZ = STEP_KHZ * float(A0.sum())     # integral of the absorption over offset in kHz (A0 peak = 1)


def _xlogx(v):
    a = np.abs(v)
    return np.where(a > 0, v * np.log(np.where(a > 0, a, 1.0)), 0.0)


def _hilbert_table(x, table):
    """Exact Hilbert transform of the piecewise-linear function through (KNOTS_KHZ, table)."""
    out = np.zeros_like(x)
    h = STEP_KHZ
    nz = np.nonzero(table)[0]
    for lo in range(0, len(nz), 64):                        # chunks keep memory small
        k = nz[lo:lo + 64]
        u = x[:, None] - KNOTS_KHZ[k][None, :]
        out += ((_xlogx(u + h) - 2 * _xlogx(u) + _xlogx(u - h)) / (np.pi * h)) @ table[k]
    return out


def absorption(x_khz, pol):
    """Absorption shape (A0 peak = 1) at offsets x_khz from f0, for polarization pol."""
    u = np.asarray(x_khz, float) - SHIFT_KHZ_PER_POL * pol
    return (np.interp(u, KNOTS_KHZ, A0, left=0.0, right=0.0)
            + pol * np.interp(u, KNOTS_KHZ, A1, left=0.0, right=0.0))


def hilbert(x_khz, pol):
    """Hilbert transform of absorption(), exactly."""
    u = np.atleast_1d(np.asarray(x_khz, float)) - SHIFT_KHZ_PER_POL * pol
    return _hilbert_table(u, A0) + pol * _hilbert_table(u, A1)


def susceptibility(f_mhz, pol, f0_mhz, chi0_per_pol):
    """Complex susceptibility chi = chi' - i chi'' at frequencies f_mhz, normalized like the deuteron and the
    notebook's Hill & Hill line: the integral of chi'' over omega is (pi/2) omega0 chi0, chi0 = chi0_per_pol * pol."""
    pol = float(pol)
    x = (np.asarray(f_mhz, float) - f0_mhz) * 1e3
    k = (np.pi / 2) * f0_mhz * 1e3 * chi0_per_pol * pol / AREA_KHZ
    return -k * hilbert(x, pol) - 1j * k * absorption(x, pol)
'''


def write_module(lines, model, path):
    Ps = np.array([ln['pol'] for ln in lines])
    fmt = lambda a: textwrap.fill(', '.join(f'{v:.5f}' for v in a), 112, initial_indent='    ',
                                  subsequent_indent='    ')
    cent_rms = 1e3 * np.std(model['centroids'] - (model['c0'] + model['slope_khz'] / 1e3 * Ps))
    src = MODULE.format(n_lines=len(lines), pmin=Ps.min(), pmax=Ps.max(),
                        n_spin=sum(ln['n'] == 1 for ln in lines), n_avg=sum(ln['n'] > 1 for ln in lines),
                        slope=model['slope_khz'], cent_rms=max(cent_rms, 0.1), max_err=np.ceil(100 * model['max_err']),
                        step=model['step'], half=GRID_HALF, half_p1=GRID_HALF + 1,
                        A0=fmt(model['A0']), A1=fmt(model['A1']))
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(src)


def write_page_data(t, pol, lines, model, f, path):
    x = 1e3 * (f - model['c0'])
    m = (x >= PAGE_REGION_KHZ[0]) & (x <= PAGE_REGION_KHZ[1])
    t_start = lines[0]['t'] - 3600
    tl = (t >= t_start)
    iso = lambda s: datetime.fromtimestamp(s, timezone.utc).strftime('%Y-%m-%d %H:%M UTC')
    data = dict(
        source='Proton event logs of a 5 T polarized target, October 2022 (212.882 MHz center, 512-point sweeps)',
        center_mhz=round(model['c0'], 5),
        step_khz=round(model['step'], 5),
        x_khz=[round(v, 3) for v in x[m]],
        lines=[dict(time=iso(ln['t']), pol=round(float(ln['pol']), 4), n=int(ln['n']), kind=ln['kind'],
                    y=[round(float(v), 7) for v in ln['y'][m]]) for ln in lines],
        timeline=dict(start=iso(t_start), hours=[round((s - t_start) / 3600, 4) for s in t[tl]],
                      pol=[round(float(p), 4) for p in pol[tl]],
                      line_hours=[round((ln['t'] - t_start) / 3600, 4) for ln in lines]),
        model=dict(shift_khz_per_pol=round(model['slope_khz'], 4), step_khz=round(model['step'], 6),
                   half=GRID_HALF, A0=[round(float(v), 5) for v in model['A0']],
                   A1=[round(float(v), 5) for v in model['A1']], max_err=round(model['max_err'], 4)),
    )
    with open(path, 'w', encoding='utf-8') as fh:
        json.dump(data, fh, separators=(',', ':'))


def main():
    directory = sys.argv[1] if len(sys.argv) > 1 else os.path.join(REPO, 'temp')
    t, pol, y, f = load_events(directory)
    lines = example_lines(t, pol, y)
    model = fit_model(lines, f)
    write_module(lines, model, os.path.join(WEB, 'proton_lineshape.py'))
    write_page_data(t, pol, lines, model, f, os.path.join(WEB, 'proton_data.json'))
    print(f"{len(t)} events, {len(lines)} example lines, shift {model['slope_khz']:.2f} kHz/P, "
          f"P=0 center {model['c0']:.5f} MHz, worst fit {100 * model['max_err']:.1f}% of peak")


if __name__ == '__main__':
    main()
